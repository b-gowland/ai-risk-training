// Downloads the site's web fonts into public/fonts so the site serves them
// itself. Before 26 Nov 2026 every page loaded them from Google Fonts, which
// sent each visitor's IP address to Google (portfolio audit, item 22).
//
// Run it only to change the fonts: `node scripts/fetch-fonts.mjs`. It writes
// public/fonts/fonts.css (the @font-face rules, same faces, weights and
// unicode ranges Google serves) and one .woff2 per file, plus each family's
// licence (all four are SIL Open Font License 1.1). Commit what it writes.
// The app (index.html) and the static pages (build-static-pages.mjs) both
// link /fonts/fonts.css. Its font URLs are relative, so the SCORM packages
// (built with a relative base) find them too.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'fonts');

// The same request index.html used to make, so nothing changes visually.
const CSS_URL = 'https://fonts.googleapis.com/css2?family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;1,6..72,400&family=Archivo:wght@400;500;600;700;800&family=Archivo+Black&family=IBM+Plex+Mono:wght@400;500&display=swap';
// A current browser's user agent, so Google returns woff2 with unicode ranges.
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const LICENCES = { 'Archivo': 'archivo', 'Archivo Black': 'archivoblack', 'Newsreader': 'newsreader', 'IBM Plex Mono': 'ibmplexmono' };

const get = async (url, as = 'text') => {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
};

const css = await get(CSS_URL);
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

// Name each file after its family, style, weight and subset. A variable font
// serves several weights from one file (Google gives it the same URL each
// time), so it is named after the first weight that uses it.
const names = new Map();
const rules = css.split('}').filter((r) => r.includes('@font-face'));
let out = '/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n';
for (const rule of rules) {
  const subset = rule.match(/\/\*\s*([\w-]+)\s*\*\//)?.[1] ?? 'all';
  const family = rule.match(/font-family:\s*'([^']+)'/)[1];
  const style = rule.match(/font-style:\s*(\w+)/)[1];
  const weight = rule.match(/font-weight:\s*(\d+)/)[1];
  const url = rule.match(/url\(([^)]+)\)/)[1];
  if (!names.has(url)) {
    const name = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${weight}-${subset}.woff2`;
    names.set(url, name);
    writeFileSync(join(OUT, name), await get(url, 'buffer'));
  }
  out += `${rule.replace(url, names.get(url)).trim()}\n}\n`;
}
writeFileSync(join(OUT, 'fonts.css'), out);

for (const [family, dir] of Object.entries(LICENCES)) {
  const text = await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${dir}/OFL.txt`);
  writeFileSync(join(OUT, `OFL-${family.replace(/\s+/g, '')}.txt`), text);
}
console.log(`Wrote ${names.size} font files, fonts.css and ${Object.keys(LICENCES).length} licences to public/fonts.`);
